// Generates Netlify's `_redirects` file at build time. Astro ignores underscore-prefixed
// files in src/pages, so the route is a one-path dynamic endpoint that emits `_redirects`.
//
// Today it only holds the 301s from /videos/<slug>-<id> to the article that is canonical for
// that video (see src/utils/video-articles.ts); those pages are no longer built. Rules from
// netlify.toml still apply alongside this file. The `!` forces the rule even if a file exists.

import type { APIRoute, GetStaticPaths } from 'astro';
import { slugify } from '~/utils/slugify';
import { getAllYouTubeVideos } from '~/utils/youtube';
import { articlePath, getVideoArticleMap } from '~/utils/video-articles';

export const getStaticPaths = (() => [{ params: { redirectsFile: '_redirects' } }]) satisfies GetStaticPaths;

export const GET: APIRoute = async () => {
  const [videos, videoArticles] = await Promise.all([getAllYouTubeVideos(), getVideoArticleMap()]);

  const rules: string[] = [];
  for (const video of videos) {
    const videoId = video.snippet?.resourceId?.videoId;
    const pair = videoId ? videoArticles.byVideoId.get(videoId) : undefined;
    if (!videoId || !pair) continue;
    rules.push(`/videos/${slugify(video.snippet.title)}-${videoId} ${articlePath(pair.articleId)} 301!`);
  }

  const body = [
    '# Generated by src/pages/[redirectsFile].ts. Do not edit; add manual redirects to netlify.toml.',
    ...rules,
    '',
  ].join('\n');

  return new Response(body, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
};
